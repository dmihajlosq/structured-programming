// Еден елемент од матрица ја дели матрицата на 4 квадранти (прикажани на сликата).
// Притоа самиот елемент кој ја дели матрицата припаѓа во четвртиот квадрант (-5 во примерот на сликата).
//
// Од стандарден влез се внесува матрица со димензии NxM (1 <= N, M < 100). Потоа се внесуваат два броеви кои претставуваат индекси
// на еден елемент од матрицата.
//
// Да се најдат сумите на секој од квадрантите и да се испечатат на стандарен излез.
// Притоа се печати сумата за првиот квадрант, па за вториот, па третиот и на крај за четвртиот. Доколку не може да се креира квадрант,
// тогаш за сумата на тој квадрант треба да се испечати 0.

#include <iostream>
using namespace std;

int main(){

    int n,m;
    cin>>n>>m;
    int matrica[n][m];
    for (int i=0;i<n;i++){
        for (int j=0;j<m;j++){
            cin>>matrica[i][j];
        }
    }
    int br1,br2;
    cin>>br1>>br2;

    int suma1=0;
    for (int i=0;i<br1;i++){
        for (int j=br2;j<m;j++){
            suma1+=matrica[i][j];
        }
    }

    int suma2=0;
    for (int i=0;i<br1;i++){
        for (int j=0;j<br2;j++){
            suma2+=matrica[i][j];
        }
    }

    int suma3=0;
    for (int i=br1;i<n;i++){
        for (int j=0;j<br2;j++){
            suma3+=matrica[i][j];
        }
    }

    int suma4=0;
    for (int i=br1;i<n;i++){
        for (int j=br2;j<m;j++){
            suma4+=matrica[i][j];
        }
    }

    cout<<suma1<<" "<<suma2<<" "<<suma3<<" "<<suma4;
}